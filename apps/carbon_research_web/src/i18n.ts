export type MessageKey = keyof typeof messages;

export function tr(key: MessageKey, locale: Locale): string {
  return messages[key][locale === "th-TH" ? 0 : 1];
}

export function findingText(code: string, locale: Locale): string {
  const key = `finding_${code}` as MessageKey;
  return key in messages ? tr(key, locale) : code;
}
